#!/usr/bin/env python3
"""Copies meteocool/core's UI strings into the app as `Core.strings`.

The native map (meteocool/NativeMap) says what core's web map says, in the
same words: every key of core's `src/locale/<lang>.json`, flattened with dots
(`compare.models`), as an ICU message (`{count, plural, one {# model} …}`)
that `CoreStrings` formats. A list becomes `key.0`, `key.1`, ….

    scripts/core-strings.py [path/to/core]   # default: ../core next to this repo

Rerun it after core's strings change and commit the result.
"""
import json
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
# The app's own languages; core has more.
LANGUAGES = ["en", "de", "da", "et", "fi", "hr", "lt", "nb", "nl", "sv"]


def find_core():
    if len(sys.argv) > 1:
        return pathlib.Path(sys.argv[1])
    for candidate in [ROOT.parent / "core", ROOT.parents[3] / "core" if len(ROOT.parents) > 3 else None,
                      pathlib.Path.home() / "meteocool" / "core"]:
        if candidate and (candidate / "src" / "locale" / "en.json").exists():
            return candidate
    sys.exit("core not found: pass its path")


def flatten(value, prefix, out):
    if isinstance(value, dict):
        for key, child in value.items():
            flatten(child, f"{prefix}.{key}" if prefix else key, out)
    elif isinstance(value, list):
        for index, child in enumerate(value):
            flatten(child, f"{prefix}.{index}", out)
    else:
        out[prefix] = str(value)


def escape(text):
    return text.replace("\\", "\\\\").replace('"', '\\"').replace("\n", "\\n")


def main():
    core = find_core()
    english = {}
    flatten(json.loads((core / "src/locale/en.json").read_text()), "", english)
    for lang in LANGUAGES:
        strings = dict(english)
        flatten(json.loads((core / f"src/locale/{lang}.json").read_text()), "", strings)
        lines = ["/* Generated by scripts/core-strings.py from meteocool/core src/locale/"
                 f"{lang}.json. Do not edit; rerun the script. */", ""]
        lines += [f'"{escape(key)}" = "{escape(strings[key])}";' for key in sorted(strings)]
        target = ROOT / "meteocool" / f"{lang}.lproj" / "Core.strings"
        target.write_text("\n".join(lines) + "\n", encoding="utf-8")
        print(f"{target.relative_to(ROOT)}: {len(strings)} strings")


if __name__ == "__main__":
    main()
